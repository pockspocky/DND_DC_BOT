"""
Combat assistance system Discord commands
Provides slash command interface for D&D combat management
"""
import discord
from discord.ext import commands
from discord import app_commands
from typing import Optional, List
from .combat_manager import CombatManager, CombatSession, CombatParticipant
from dice.advanced_roller import advanced_roller
import logging

logger = logging.getLogger(__name__)

class CombatCommands(commands.Cog):
    """Combat assistance command group"""
    
    def __init__(self, bot: commands.Bot):
        self.bot = bot
        self.combat_manager = CombatManager()
        self.dice_roller = advanced_roller
        
    async def cog_load(self):
        """Initialize when extension is loaded"""
        logger.info("Combat assistance command module loaded")
        
    async def cog_unload(self):
        """Cleanup when extension is unloaded"""
        logger.info("Combat assistance command module unloaded")
    

    
    def _create_combat_embed(self, combat: CombatSession, participants: List[CombatParticipant]) -> discord.Embed:
        """Create combat status embed message"""
        embed = discord.Embed(
            title=f"⚔️ Combat: {combat.name}",
            description=f"Round {combat.current_round}",
            color=discord.Color.red()
        )
        
        if participants:
            # Current turn character
            current_participant = participants[combat.current_turn] if combat.current_turn < len(participants) else None
            if current_participant:
                embed.add_field(
                    name="🎯 Current Turn",
                    value=f"{current_participant.type_icon} **{current_participant.name}**",
                    inline=False
                )
            
            # Initiative order
            initiative_list = []
            for i, participant in enumerate(participants):
                status = "👈" if i == combat.current_turn else "　"
                hp_bar = self._create_hp_bar(participant)
                initiative_list.append(
                    f"{status} {participant.status_icon} **{participant.name}** ({participant.initiative}) - {hp_bar}"
                )
            
            embed.add_field(
                name="📋 Initiative Order",
                value="\n".join(initiative_list) if initiative_list else "No participants",
                inline=False
            )
        else:
            embed.add_field(
                name="📋 Participants",
                value="No participants yet, use `/add` to add",
                inline=False
            )
        
        embed.set_footer(text=f"Combat ID: {combat.id} | DM permission required")
        return embed
    
    def _create_hp_bar(self, participant: CombatParticipant) -> str:
        """Create HP bar"""
        percentage = participant.hp_percentage
        bar_length = 10
        filled = int(bar_length * percentage / 100)
        empty = bar_length - filled
        
        bar = "█" * filled + "░" * empty
        return f"{participant.current_hp}/{participant.max_hp} HP |{bar}|"
    
    async def _check_dm_permission(self, interaction: discord.Interaction) -> bool:
        """Check DM permission and respond"""
        if not isinstance(interaction.user, discord.Member):
            await interaction.response.send_message("❌ This command can only be used in a server", ephemeral=True)
            return False
            
        if not await self.combat_manager.is_dm(interaction.user):
            await interaction.response.send_message("❌ Only DMs can use this command", ephemeral=True)
            return False
            
        return True
    
    # ===== Combat Management Commands =====
    
    @app_commands.command(name="cs", description="Start a new combat session")
    @app_commands.describe(name="Combat name (optional, auto-generated by default)")
    async def start_combat(self, interaction: discord.Interaction, name: Optional[str] = None):
        """Start new combat"""
        if not await self._check_dm_permission(interaction):
            return
        
        # Check if there's already an active combat
        existing = await self.combat_manager.get_active_combat(
            interaction.guild_id, interaction.channel_id
        )
        if existing:
            embed = discord.Embed(
                title="⚠️ Active Combat Exists",
                description=f"Combat `{existing.name}` is already in progress in this channel\nUse `/ce` to end the current combat",
                color=discord.Color.orange()
            )
            await interaction.response.send_message(embed=embed, ephemeral=True)
            return
        
        # Generate default combat name
        if not name:
            import datetime
            timestamp = datetime.datetime.now().strftime("%m-%d %H:%M")
            name = f"Combat {timestamp}"
        
        # Create new combat
        combat = await self.combat_manager.start_combat(
            interaction.guild_id, interaction.channel_id, interaction.user.id, name
        )
        
        if combat:
            embed = discord.Embed(
                title="⚔️ Combat Started!",
                description=f"Combat `{name}` has begun",
                color=discord.Color.green()
            )
            embed.add_field(
                name="📝 Next Steps",
                value="Use `/add` to add participants\nUse `/st` to view combat status",
                inline=False
            )
            embed.set_footer(text=f"Combat ID: {combat.id}")
            await interaction.response.send_message(embed=embed)
            
            logger.info(f"User {interaction.user} started combat in channel {interaction.channel_id}: {name}")
        else:
            await interaction.response.send_message("❌ Failed to create combat, please try again later", ephemeral=True)
    
    @app_commands.command(name="ce", description="End the current combat")
    async def end_combat(self, interaction: discord.Interaction):
        """End combat"""
        if not await self._check_dm_permission(interaction):
            return
        
        combat = await self.combat_manager.get_active_combat(
            interaction.guild_id, interaction.channel_id
        )
        
        if not combat:
            await interaction.response.send_message("❌ No active combat in this channel", ephemeral=True)
            return
        
        success = await self.combat_manager.end_combat(combat.id)
        
        if success:
            embed = discord.Embed(
                title="🏁 Combat Ended",
                description=f"Combat `{combat.name}` has ended",
                color=discord.Color.blue()
            )
            embed.add_field(
                name="📊 Combat Statistics",
                value=f"Total rounds: {combat.current_round}\nParticipants: {len(combat.participants)}",
                inline=False
            )
            embed.add_field(
                name="📚 View Logs",
                value="Use `/log` to view detailed combat records",
                inline=False
            )
            await interaction.response.send_message(embed=embed)
            
            logger.info(f"User {interaction.user} ended combat: {combat.name}")
        else:
            await interaction.response.send_message("❌ Failed to end combat, please try again later", ephemeral=True)
    
    @app_commands.command(name="st", description="View current combat status")
    async def st(self, interaction: discord.Interaction):
        """View combat status"""
        combat = await self.combat_manager.get_active_combat(
            interaction.guild_id, interaction.channel_id
        )
        
        if not combat:
            embed = discord.Embed(
                title="ℹ️ No Active Combat",
                description="No combat in progress in this channel\nUse `/cs` to start a new combat",
                color=discord.Color.blue()
            )
            await interaction.response.send_message(embed=embed, ephemeral=True)
            return
        
        participants = await self.combat_manager.get_participants(combat.id)
        embed = self._create_combat_embed(combat, participants)
        
        await interaction.response.send_message(embed=embed)
    
    # ===== Participant Management Commands =====
    
    @app_commands.command(name="add", description="Add a combat participant")
    @app_commands.describe(
        name="Character name",
        max_hp="Maximum hit points",
        initiative="Initiative value",
        ac="Armor class (optional)",
        is_npc="Is this an NPC? (optional)"
    )
    async def add(
        self, interaction: discord.Interaction, 
        name: str, max_hp: int, initiative: int,
        ac: Optional[int] = 10, is_npc: Optional[bool] = False
    ):
        """Add participant"""
        if not await self._check_dm_permission(interaction):
            return
        
        combat = await self.combat_manager.get_active_combat(
            interaction.guild_id, interaction.channel_id
        )
        
        if not combat:
            await interaction.response.send_message("❌ No active combat in this channel", ephemeral=True)
            return
        
        # Validate values
        if max_hp <= 0:
            await interaction.response.send_message("❌ Maximum HP must be greater than 0", ephemeral=True)
            return
        
        if len(name) > 50:
            await interaction.response.send_message("❌ Character name too long (max 50 characters)", ephemeral=True)
            return
        
        participant = await self.combat_manager.add_participant(
            combat.id, name, max_hp, initiative, ac, is_npc
        )
        
        if participant:
            embed = discord.Embed(
                title="✅ Participant Added",
                description=f"{participant.type_icon} **{name}** joined the combat!",
                color=discord.Color.green()
            )
            embed.add_field(name="Initiative", value=str(initiative), inline=True)
            embed.add_field(name="Hit Points", value=f"{max_hp}/{max_hp}", inline=True)
            embed.add_field(name="Armor Class", value=str(ac), inline=True)
            
            await interaction.response.send_message(embed=embed)
            
            logger.info(f"User {interaction.user} added participant: {name}")
        else:
            await interaction.response.send_message("❌ Failed to add participant, name may already exist", ephemeral=True)
    
