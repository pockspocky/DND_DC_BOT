    @app_commands.command(name="dmg", description="Deal damage to a character")
    @app_commands.describe(
        target="Target character name",
        expression="Damage expression (e.g., 2d6+3) or fixed value",
        attacker="Attacker name (optional)"
    )
    async def apply_dmg(
        self, interaction: discord.Interaction, 
        target: str, expression: str, attacker: Optional[str] = None
    ):
        """Deal damage"""
        if not await self._check_dm_permission(interaction):
            return
        
        combat = await self.combat_manager.get_active_combat(
            interaction.guild_id, interaction.channel_id
        )
        
        if not combat:
            await interaction.response.send_message("❌ No active combat in this channel", ephemeral=True)
            return
        
        # If no attacker specified, use current turn character name
        if attacker is None:
            participants = await self.combat_manager.get_participants(combat.id)
            if participants and combat.current_turn < len(participants):
                attacker = participants[combat.current_turn].name
            else:
                attacker = interaction.user.display_name
        
        # Parse damage value
        try:
            # Try to parse as number directly
            if expression.isdigit():
                dmg = int(expression)
                dice_result = f"Fixed damage: {dmg}"
            else:
                # Use dice system
                result = await self.dice_roller.roll(
                    expression, interaction.user.id, interaction.guild_id or 0, interaction.channel_id or 0
                )
                dmg = result.final_value
                dice_result = f"{expression}: {result.final_value}"
        except Exception as e:
            await interaction.response.send_message(f"❌ Invalid damage expression: {expression}", ephemeral=True)
            return
        
        if dmg < 0:
            await interaction.response.send_message("❌ Damage cannot be negative", ephemeral=True)
            return
        
        participant = await self.combat_manager.apply_damage(
            combat.id, target, dmg, attacker, expression, dice_result
        )
        
        if participant:
            embed = discord.Embed(
                title="💥 Damage Applied",
                description=f"**{attacker}** → **{target}**",
                color=discord.Color.red()
            )
            embed.add_field(name="🎲 Roll Result", value=dice_result, inline=False)
            embed.add_field(name="💔 Damage", value=f"{dmg} points", inline=True)
            
            hp_bar = self._create_hp_bar(participant)
            embed.add_field(name="💖 Remaining HP", value=hp_bar, inline=False)
            
            if participant.current_hp <= 0:
                embed.add_field(name="💀 Status", value=f"**{target}** is down!", inline=False)
            
            await interaction.response.send_message(embed=embed)
            
            logger.info(f"Dealt {dmg} damage to {target}")
        else:
            await interaction.response.send_message(f"❌ Character not found: {target}", ephemeral=True)
    
