    async def next(self, interaction: discord.Interaction):
        """Next turn"""
        if not await self._check_dm_permission(interaction):
            return
        
        combat = await self.combat_manager.get_active_combat(
            interaction.guild_id, interaction.channel_id
        )
        
        if not combat:
            await interaction.response.send_message("❌ No active combat in this channel", ephemeral=True)
            return
        
        current_participant = await self.combat_manager.next_turn(combat.id)
        
        if current_participant:
            embed = discord.Embed(
                title="🔄 Turn Changed",
                description=f"It's now **{current_participant.name}**'s turn",
                color=discord.Color.gold()
            )
            
            # Refresh combat status after update
            updated_combat = await self.combat_manager.get_active_combat(
                interaction.guild_id, interaction.channel_id
            )
            if updated_combat:
                embed.add_field(
                    name="⏰ Current Status",
                    value=f"Round {updated_combat.current_round}",
                    inline=True
                )
            
            hp_bar = self._create_hp_bar(current_participant)
            embed.add_field(
                name="💖 Hit Points",
                value=hp_bar,
                inline=False
            )
            
            await interaction.response.send_message(embed=embed)
            
            logger.info(f"Combat turn advanced to: {current_participant.name}")
        else:
            await interaction.response.send_message("❌ Failed to advance turn, check if there are participants", ephemeral=True)
    
